"""
script.py — Generate Anvil Slurm job scripts for the SPIDA pipeline.

Each (EXPERIMENT, REGION) gets a directory {output_dir}/{EXP_N}/{REG_N}/ with the filled templates of
anvil_templates/templates/ and a chain.sh that submits them with --dependency=afterok. The step bodies
follow aws_templates/aws_s3_template/ (generated by script_aws.py); only the SBATCH headers, modules and
the job-local copy of SPIDA differ.

The config JSON (--config_path) is passed to every SPIDA command as --config and provides
PROCESSED_ROOT_PATH, SEGMENTATION_OUT_PATH, CUTOFFS_PATH (required) and MMC_DIR / REGION_LABELS (optional).
Deconvolved planes go to {PROCESSED_ROOT_PATH}/{EXPERIMENT}/out/{REGION}/decon-images/. Step 5
(MapMyCells) is written only with --mmc_reference.

Usage
-----
pixi run -e preprocessing python slurm_scripts/script.py 202511071313_BICAN-4x1-HIPU-E-01_VMSC31910 \\
    --region_name region_UCI-5224 --lab salk --config_path HIPP_test/config/config_3d.json \\
    --output_dir HIPP_test/3d/image_processing --seg_mode 3d_true --decon_iter 25 \\
    --mmc_reference hippocampus-franjic-deep --cellpose_gpu_time 6:00:00
"""

import sys
import json
import stat
from pathlib import Path

import click

from spida._constants import rename_exp_salk, rename_reg_salk, rename_exp_ucsd, rename_reg_ucsd

_SCRIPT_DIR = Path(__file__).parent
_TEMPLATE_DIR = _SCRIPT_DIR / "anvil_templates" / "templates"
_SPIDA_ROOT = _SCRIPT_DIR.parent


def _parse_list(arg: str) -> list:
    """Parse a comma-separated list CLI argument."""
    return None if arg is None else arg.split(",")


@click.command("config-anvil")
@click.argument("experiment_name")
@click.option("--region_name", "-r", default=None, help="Full region name (e.g. region_UCI-5224). If omitted, every region_* dir under --data_path.")
@click.option("--lab", default=None, type=click.Choice([None, "salk", "ucsd"], case_sensitive=False), help="Naming convention for EXP_N / REG_N (default: full names).")
@click.option("data_path", "--data_path", type=click.Path(exists=True, dir_okay=True, path_type=Path), default=None, help="The experiment's out/ dir; needed when --region_name is omitted.")
@click.option("--brain_region", "-b", required=True, help="Brain region for the site figures (e.g. HIPP).")
@click.option("--naming_map", type=click.Path(exists=True, dir_okay=False, path_type=Path), default=None, help="Site naming map CSV (optional).")
@click.option("--config_path", type=click.Path(exists=True, dir_okay=False, path_type=Path), required=True, help="SPIDA config JSON passed to every command as --config.")
@click.option("--output_dir", type=click.Path(dir_okay=True, path_type=Path), required=True, help="Root for the generated job scripts ({output_dir}/{EXP_N}/{REG_N}/).")
@click.option("--log_dir", type=click.Path(dir_okay=True, path_type=Path), default=None, help="SLURM log dir (default: {output_dir}/logs/{EXP_N}).")
@click.option("--template_dir", type=click.Path(exists=True, dir_okay=True, path_type=Path), default=_TEMPLATE_DIR, show_default=True)
@click.option("--spida_root", type=click.Path(exists=True, dir_okay=True, path_type=Path), default=_SPIDA_ROOT, show_default=True, help="SPIDA checkout each job copies and runs.")
@click.option("--exp_n", default=None, help="Override the derived short experiment name.")
@click.option("--reg_n", default=None, help="Override the derived short region name (single --region_name only).")
@click.option("--steps", type=_parse_list, default="all", show_default=True, help="Comma-separated steps for chain.sh (1-5); 'all' = 1-4, plus 5 with --mmc_reference.")
@click.option("--proseg_cutoffs_path", default=None, help="QC cutoffs JSON for proseg_cell filtering (default: CUTOFFS_PATH in the config).")
@click.option("--overwrite", is_flag=True, default=False, help="Pass --overwrite to every writing command (re-runs).")
@click.option("--tissue_raster/--no_tissue_raster", "tissue_raster", default=True, show_default=True, help="--no_tissue_raster: step 1 writes only the store's mask (another chain writes tissue_mask.tif).")
@click.option("--force_2d_segmentation", is_flag=True, default=False, help="Segment the middle z-slice (_z3.decon.tif) instead of all deconvolved planes.")
@click.option("--decon_iter", type=int, default=100, show_default=True, help="deconwolf Richardson-Lucy iterations.")
@click.option("--decon_tilesize", type=int, default=1000, show_default=True, help="deconwolf's internal tile size (0 = untiled).")
@click.option("--decon_psigma", type=float, default=None, help="deconwolf --psigma (needs --decon_tilesize 0).")
@click.option("--seg_mode", type=click.Choice(["2d", "3d_stitched", "3d_true"], case_sensitive=False), default="3d_stitched", show_default=True)
@click.option("--cellpose_model", type=click.Choice(["cpsam", "cpsam_v2", "cpdino", "cpdino-vitb"], case_sensitive=False), default="cpsam", show_default=True)
@click.option("--gpu_tile_size", default="auto", show_default=True, help="'auto', an int, '<y>x<x>', or 'none' (whole region in one model.eval).")
@click.option("--gpu_tile_overlap", type=int, default=500, show_default=True)
@click.option("--tissue_mask/--no_tissue_mask", "use_tissue_mask", default=True, show_default=True, help="Gate step 3a to tissue_mask.tif (explicit path: a missing mask fails the job).")
@click.option("--tissue_rho_min", type=float, default=5.0, show_default=True)
@click.option("--mmc_reference", default=None, help="MapMyCells reference; enables step 5.")
@click.option("--mmc_store_path", default=None, help="MapMyCells reference store (default: MMC_DIR in the config).")
@click.option("--mmc_args", default="--n_cpu 8 --bootstrap_iterations 100", show_default=True, help="Further mmc-annotation-region options, verbatim.")
# Wall times. Defaults from measured runs (2026, Anvil): start <= 24 min, decon (3D, 7 planes) <= 4:49,
# cellpose process+load+filter+setup ~41 min (THM2 gold), proseg chain <= 47 min (THM2), MMC <= 6 min.
@click.option("--start_time", default="0:45:00", show_default=True)
@click.option("--decon_time", default="5:00:00", show_default=True)
@click.option("--cellpose_gpu_time", default="4:00:00", show_default=True, help="Size from a measured run of the same --seg_mode (3d_true on a full HIPu-size region: ~14 h, Amit 2026-10-30 -> 16:00:00).")
@click.option("--cellpose_cpu_time", default="1:30:00", show_default=True)
@click.option("--proseg_time", default="1:30:00", show_default=True)
@click.option("--mmc_time", default="0:20:00", show_default=True)
def config_templates(
    experiment_name, region_name, lab, data_path, brain_region, naming_map, config_path, output_dir, log_dir, template_dir,
    spida_root, exp_n, reg_n, steps, proseg_cutoffs_path, overwrite, tissue_raster, force_2d_segmentation,
    decon_iter, decon_tilesize, decon_psigma, seg_mode, cellpose_model, gpu_tile_size, gpu_tile_overlap,
    use_tissue_mask, tissue_rho_min, mmc_reference, mmc_store_path, mmc_args,
    start_time, decon_time, cellpose_gpu_time, cellpose_cpu_time, proseg_time, mmc_time,
):
    """Generate Anvil Slurm job scripts for EXPERIMENT_NAME."""
    if region_name is None and data_path is None:
        click.echo("ERROR: provide --region_name, or --data_path to discover every region_* dir.", err=True)
        sys.exit(1)

    config = json.loads(Path(config_path).read_text())
    ROOT_DIR, SEGMENTATION_DIR, CUTOFFS_PATH = (config.get(k) for k in
                                                ("PROCESSED_ROOT_PATH", "SEGMENTATION_OUT_PATH", "CUTOFFS_PATH"))
    missing = [k for k, v in (("PROCESSED_ROOT_PATH", ROOT_DIR), ("SEGMENTATION_OUT_PATH", SEGMENTATION_DIR),
                              ("CUTOFFS_PATH", CUTOFFS_PATH)) if v is None]
    if missing:
        click.echo(f"ERROR: {config_path} is missing required keys: {missing}", err=True)
        sys.exit(1)
    if config.get("REGION_LABELS") is None:
        click.echo(f"  WARNING: {config_path} has no REGION_LABELS: donors become the region name without 'region_'.")
    mmc_store_path = mmc_store_path or config.get("MMC_DIR")
    if mmc_reference is not None and mmc_store_path is None:
        click.echo("ERROR: --mmc_reference needs --mmc_store_path or MMC_DIR in the config.", err=True)
        sys.exit(1)
    if decon_psigma is not None and decon_tilesize and decon_tilesize > 0:
        click.echo(f"  WARNING: --decon_psigma {decon_psigma} is ignored by deconwolf while --decon_tilesize is set.", err=True)

    # names
    lab = lab.lower() if lab else None
    if exp_n is None:
        exp_n = {"salk": rename_exp_salk, "ucsd": rename_exp_ucsd}.get(lab, lambda x: x)(experiment_name)
    if region_name is not None:
        region_names = [region_name]
    else:
        region_names = sorted(p.name for p in Path(data_path).glob("region_*") if p.is_dir())
        click.echo(f"Discovered {len(region_names)} regions: {region_names}")

    # steps
    if len(steps) == 1 and steps[0] == "all":
        flags = {s: "true" for s in "1234"}
        flags["5"] = "true" if mmc_reference else "false"
    else:
        steps = [x.strip() for x in steps]
        flags = {s: ("true" if s in steps else "false") for s in "12345"}
    if flags["5"] == "true" and not mmc_reference:
        click.echo("ERROR: step 5 (MapMyCells) needs --mmc_reference.", err=True)
        sys.exit(1)

    # segmentation / decon arguments (same rules as script_aws.py)
    image_ext = "_z3.decon.tif" if force_2d_segmentation else ".decon.tif"
    tiling_off = str(gpu_tile_size).lower() in ("", "none", "off", "false")
    if not tiling_off and str(gpu_tile_size).lower() == "auto" and not use_tissue_mask:
        click.echo("ERROR: --gpu_tile_size=auto needs a tissue mask; drop --no_tissue_mask or give a tile size.", err=True)
        sys.exit(1)
    seg_extra_args = "" if tiling_off else f"--gpu_tile_size={gpu_tile_size} --gpu_tile_overlap={gpu_tile_overlap}"
    decon_pairs = [("iter", decon_iter)] + ([("tilesize", decon_tilesize)] if decon_tilesize and decon_tilesize > 0 else []) \
        + ([("psigma", decon_psigma)] if decon_psigma is not None else [])
    decon_filter_args = "".join(f"--transform_args {k} {v} " for k, v in decon_pairs)
    click.echo(f"  segmentation: seg_mode={seg_mode} model={cellpose_model} image_ext={image_ext} "
               f"tiling={'off' if tiling_off else gpu_tile_size} tissue_mask={'on' if use_tissue_mask else 'off'}")

    for current_region in region_names:
        if reg_n is not None and len(region_names) == 1:
            current_reg_n = reg_n
        else:
            current_reg_n = {"salk": rename_reg_salk, "ucsd": rename_reg_ucsd}.get(lab, lambda x: x)(current_region)
        region_out = f"{ROOT_DIR}/{experiment_name}/out/{current_region}"
        job_dir = Path(output_dir) / exp_n / current_reg_n
        job_dir.mkdir(parents=True, exist_ok=True)
        logs = Path(log_dir) if log_dir else Path(output_dir) / "logs" / exp_n
        logs.mkdir(parents=True, exist_ok=True)
        click.echo(f"\nConfiguring {exp_n} / {current_reg_n} ({current_region}) -> {job_dir}")

        values = dict(
            EXPERIMENT=experiment_name, REGION=current_region, BR=brain_region, EXP_N=exp_n, REG_N=current_reg_n,
            NAMING_MAP_ARG=f"\\\n    --naming-map {naming_map}" if naming_map else "",
            ROOT_DIR=ROOT_DIR, SEGMENTATION_DIR=SEGMENTATION_DIR, CUTOFFS_PATH=CUTOFFS_PATH,
            PROSEG_CUTOFFS_PATH=proseg_cutoffs_path or CUTOFFS_PATH, CONFIG_PATH=str(config_path),
            DATA_ORG_PATH=f"{ROOT_DIR}/{experiment_name}/raw/dataorganization.csv",
            DECON_DIR=f"{region_out}/decon-images", JOB_DIR=str(job_dir), LOG_DIR=str(logs), SPIDA_ROOT=str(spida_root),
            STEP_1=flags["1"], STEP_2=flags["2"], STEP_3=flags["3"], STEP_4=flags["4"], STEP_5=flags["5"],
            OVERWRITE_ARG="--overwrite" if overwrite else "", TISSUE_RASTER_ARG="" if tissue_raster else "--no_raster ",
            TISSUE_MASK_ARG=f"--tissue_mask_path {region_out}/images/tissue_mask.tif " if use_tissue_mask else "",
            TISSUE_RHO_MIN=tissue_rho_min, IMAGE_EXT=image_ext, SEG_MODE=seg_mode, CELLPOSE_MODEL=cellpose_model,
            SEG_EXTRA_ARGS=seg_extra_args, DECON_FILTER_ARGS=decon_filter_args,
            MMC_REFERENCE=mmc_reference or "", MMC_STORE_PATH=mmc_store_path or "", MMC_ARGS=mmc_args,
            T_START=start_time, T_DECON=decon_time, T_CELLPOSE_GPU=cellpose_gpu_time, T_CELLPOSE_CPU=cellpose_cpu_time,
            T_PROSEG=proseg_time, T_MMC=mmc_time,
        )
        for template_file in sorted(Path(template_dir).glob("*.sh")):
            if template_file.name.startswith("5_") and not mmc_reference:
                continue  # no reference for this brain region
            out_path = job_dir / template_file.name
            out_path.write_text(template_file.read_text().format(**values))
            out_path.chmod(out_path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP)
            click.echo(f"  Written: {out_path.name}")
        click.echo(f"  Done — submit with: bash {job_dir}/chain.sh")


if __name__ == "__main__":
    config_templates()
